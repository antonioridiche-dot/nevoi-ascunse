import { readFileSync, writeFileSync } from "node:fs";
import { join, dirname } from "node:path";
import { fileURLToPath } from "node:url";
const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const html = readFileSync(join(root, "client", "dist", "index.html"), "utf8");
const out = "// Generated by scripts/gen-spa.mjs (run after vite build)." + String.fromCharCode(10) +
  "export const INDEX_HTML: string = " + JSON.stringify(html) + ";" + String.fromCharCode(10);
writeFileSync(join(root, "worker", "spa-html.ts"), out);
console.log("spa-html.ts generated (" + html.length + " bytes)");